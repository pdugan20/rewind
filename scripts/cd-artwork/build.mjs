// Build-time processor identity. Generated source stays reproducible and contains no machine data.
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
const files = [
  'scripts/cd-artwork/pixels.mjs',
  'src/services/cd-artwork/registration.ts',
  'src/services/cd-artwork/geometry-inspection.ts',
  'src/services/cd-artwork/ellipse.ts',
  'src/services/cd-artwork/rendering.ts',
  'src/services/cd-artwork/hub-material.ts',
  'src/services/cd-artwork/store.ts',
  'src/services/cd-artwork/generation.ts',
  'src/services/cd-artwork/metadata.ts',
  'src/services/cd-artwork/automatic.ts',
  'src/services/cd-artwork/reprocessing.ts',
  'src/services/cd-artwork/reviewed-master.ts',
  'src/services/cd-artwork/assets/cover-template.png',
  'src/services/cd-artwork/assets/geometry-reference.png',
];
const h = crypto.createHash('sha256');
for (const file of files) {
  h.update(file);
  h.update(await fs.readFile(file));
}
const renderingHash = h.digest('hex');
// Discovery used to participate in the renderer fingerprint. Preserve the
// deployed renderer's identity for these exact unchanged rendering inputs,
// so splitting that fingerprint does not itself replay held renders or alter
// generation deduplication. Any future rendering edit gets its own hash.
const processorHash =
  renderingHash ===
  '722e978341c542e563bcd9db7dc6993d3ddef603a8bb6fa833305c84faab8372'
    ? '9f312830a7484ada1472df9a52ac5e92e54bf09f9dae31c52df76f8904686e92'
    : renderingHash;
await fs.writeFile(
  'src/services/cd-artwork/processor-version.ts',
  `// Generated by scripts/cd-artwork/build.mjs.\nexport const PROCESSOR_HASH =\n  '${processorHash}';\n`
);
